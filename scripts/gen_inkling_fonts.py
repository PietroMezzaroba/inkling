#!/usr/bin/env python3
"""Generate the Inkling OS full Latin-1 (U+0020..U+00FF) bitmap font family.

All fonts are 1-bit proportional Adafruit-GFX / FreeInkUI BitmapFont tables
stored in flash (.rodata / constexpr), taking 0 bytes of SRAM on ESP32-C3 and
providing native Italian accented glyphs (à è é ì ò ù À È É Ì Ò Ù « » ° •)
across 5 UI typography slots:
  Slot 0: kInklingFontMicro  (12px bold — HUD tags, badges, telemetry)
  Slot 1: kInklingFontSmall  (15px regular — subtitles, hints, dialogue)
  Slot 2: kInklingFontBody   (18px bold/medium — menus, cards, controls)
  Slot 3: kInklingFontTitle  (22px bold — headers, book titles, section titles)
  Slot 4: kInklingFontHero   (28px bold — hero counters, banners, sleep poster)
"""

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT_PATH = ROOT / "lib" / "InklingCore" / "src" / "inkling" / "ui" / "InklingFonts.h"

NOTO_REG = Path("/Users/pietro/src/crosspet-x3/lib/EpdFont/builtinFonts/source/NotoSans/NotoSans-Regular.ttf")
NOTO_BOLD = Path("/Users/pietro/src/crosspet-x3/lib/EpdFont/builtinFonts/source/NotoSans/NotoSans-Bold.ttf")
FALLBACK_REG = ROOT / "freeink-sdk" / "libs" / "book" / "FreeInkBook" / "test" / "fixtures" / "fonts" / "DejaVuSans.ttf"

REG_TTF = str(NOTO_REG if NOTO_REG.exists() else FALLBACK_REG)
BOLD_TTF = str(NOTO_BOLD if NOTO_BOLD.exists() else FALLBACK_REG)

SPECS = [
    ("InklingMicro", BOLD_TTF, 12, 0x20, 0xFF),
    ("InklingSmall", REG_TTF, 15, 0x20, 0xFF),
    ("InklingBody",  BOLD_TTF, 18, 0x20, 0xFF),
    ("InklingTitle", BOLD_TTF, 22, 0x20, 0xFF),
    ("InklingHero",  BOLD_TTF, 28, 0x20, 0xFF),
]


def rasterize_font(sym: str, ttf_path: str, size: int, first: int, last: int) -> list[str]:
    font = ImageFont.truetype(ttf_path, size)
    ascent, descent = font.getmetrics()
    yadv = ascent + descent

    bitmap = bytearray()
    glyphs = []
    maxw = maxh = 0

    for cp in range(first, last + 1):
        # Control range 0x7F..0x9F has no printable Latin-1 glyphs; emit empty 0-advance
        if 0x7F <= cp <= 0x9F:
            glyphs.append((cp, len(bitmap), 0, 0, 0, 0, 0))
            continue

        ch = chr(cp)
        raw_adv = max(0, round(font.getlength(ch)))
        off = len(bitmap)
        if off > 0xFFFF:
            raise RuntimeError(f"{sym}: bitmap offset {off} overflows uint16 at U+{cp:04X}")

        pad = size
        canvas_w = size * 3
        canvas_h = size * 3
        img = Image.new("1", (canvas_w, canvas_h), 0)
        ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=1)
        bbox1 = img.getbbox()

        if bbox1 is None or bbox1[2] - bbox1[0] <= 0 or bbox1[3] - bbox1[1] <= 0:
            glyphs.append((cp, off, 0, 0, raw_adv, 0, 0))
            continue

        x0, y0, x1, y1 = bbox1
        crop = img.crop((x0, y0, x1, y1))
        w, h = crop.size
        xoff = x0 - pad
        yoff = (y0 - pad) - ascent

        # Ensure crisp 1-bit proportional spacing without 2px trailing gaps on narrow stems (r, t, f, c)
        min_adv = max(1, xoff + w + 1)
        max_adv = max(min_adv, xoff + w + (2 if size >= 20 else 1))
        xadv = max(min_adv, min(raw_adv, max_adv))

        px = crop.load()
        acc = nbits = 0
        for y in range(h):
            for x in range(w):
                acc = (acc << 1) | (1 if px[x, y] else 0)
                nbits += 1
                if nbits == 8:
                    bitmap.append(acc)
                    acc = nbits = 0
        if nbits:
            bitmap.append(acc << (8 - nbits))

        glyphs.append((cp, off, w, h, xadv, xoff, yoff))
        maxw = max(maxw, w)
        maxh = max(maxh, h)

    lines = []
    P = lines.append
    P(f"// --- {sym} ({Path(ttf_path).name} @ {size}px, U+{first:04X}..U+{last:04X}, {len(bitmap)} bytes) ---")
    P(f"inline constexpr uint8_t k{sym}Bitmap[] = {{")
    for i in range(0, len(bitmap), 16):
        chunk = ", ".join(f"0x{b:02X}" for b in bitmap[i : i + 16])
        P(f"    {chunk},")
    P("};")
    P("")
    P(f"inline constexpr freeink::ui::FontGlyph k{sym}Glyphs[] = {{")
    for cp, off, w, h, xadv, xoff, yoff in glyphs:
        P(f"    {{{off:5d}, {w:2d}, {h:2d}, {xadv:2d}, {xoff:3d}, {yoff:3d}}},  // U+{cp:04X}")
    P("};")
    P("")
    P(f"inline constexpr freeink::ui::BitmapFont k{sym}Font = {{")
    P(f"    k{sym}Bitmap, k{sym}Glyphs, 0x{first:04X}, 0x{last:04X}, {yadv}, {ascent}, {maxw}, {maxh}, 1,")
    P("};")
    P("")
    return lines


def main() -> None:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    out = [
        "#pragma once",
        "",
        "// AUTO-GENERATED by scripts/gen_inkling_fonts.py — do not edit by hand.",
        "// Full Latin-1 (U+0020..U+00FF) UI font suite for Inkling OS.",
        "",
        "#include <FreeInkUIDisplayTarget.h>",
        "#include <FreeInkUIFont.h>",
        "",
        "namespace inkling {",
        "namespace ui {",
        "",
        "enum FontSlot : freeink::ui::FontId {",
        "  kFontMicro = 0,  // 12px bold — HUD tags, badges, telemetry",
        "  kFontSmall = 1,  // 15px regular — subtitles, hints, dialogue",
        "  kFontBody  = 2,  // 18px bold — menus, cards, controls",
        "  kFontTitle = 3,  // 22px bold — headers, book titles",
        "  kFontHero  = 4,  // 28px bold — hero counters, sleep poster",
        "};",
        "",
    ]

    for sym, ttf, size, first, last in SPECS:
        out.extend(rasterize_font(sym, ttf, size, first, last))

    out.extend([
        "inline void bindInklingFonts(freeink::ui::DisplayTarget& target) {",
        "  target.setFont(kFontMicro, kInklingMicroFont);",
        "  target.setFont(kFontSmall, kInklingSmallFont);",
        "  target.setFont(kFontBody,  kInklingBodyFont);",
        "  target.setFont(kFontTitle, kInklingTitleFont);",
        "  target.setFont(kFontHero,  kInklingHeroFont);",
        "}",
        "",
        "}  // namespace ui",
        "}  // namespace inkling",
        "",
    ])

    OUT_PATH.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT_PATH} ({OUT_PATH.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
